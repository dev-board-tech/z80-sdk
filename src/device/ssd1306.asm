ssd1306_get_y:
	ld a, 64;
	ret

;-----------------------------------------------------------------------
; Required:
; a = command to send
; hl = buffer address
; Return:
; Flag C = 0' if success, 1' if error
; Altered:
; a
;-----------------------------------------------------------------------
i2cs_ssd1306_WrCmd:
	push de
	ld d, a
	ld a, SSD1306_I2C_ADDRESS
	ld (SSD1306_CBUFFER + 0), a
	ld a, 0
	ld (SSD1306_CBUFFER + 1), a
	ld a, d
	ld (SSD1306_CBUFFER + 2), a
	ld de, 3
	call i2cs_W
	pop de
	ret
;-----------------------------------------------------------------------
; Required:
; hl = buffer address
; Return:
; Flag C = 0' if success, 1' if error
; Altered:
; a
;-----------------------------------------------------------------------
i2cs_ssd1306_WrBuffer:
	push bc
	push hl
	
	ld hl, SSD1306_CBUFFER
	
	ld a, SSD1306_COLUMNADDR
	call i2cs_ssd1306_WrCmd
	ld a, 0
	call i2cs_ssd1306_WrCmd
	ld a, 127
	call i2cs_ssd1306_WrCmd
	
	ld a, SSD1306_PAGEADDR
	call i2cs_ssd1306_WrCmd
	ld a, 0
	call i2cs_ssd1306_WrCmd
	ld a, 7
	call i2cs_ssd1306_WrCmd
	
	;ld a, 0xAA
	;ld (SSD1306_VBUFFER + SSD1306_VBUFFER_OFFSET + 0), a
	;ld a, 0x55
	;ld (SSD1306_VBUFFER + SSD1306_VBUFFER_OFFSET + 1), a
	;ld a, 0xAA
	;ld (SSD1306_VBUFFER + SSD1306_VBUFFER_OFFSET + 2), a
	;ld a, 0x55
	;ld (SSD1306_VBUFFER + SSD1306_VBUFFER_OFFSET + 3), a
	;ld a, 0xAA
	;ld (SSD1306_VBUFFER + SSD1306_VBUFFER_OFFSET + 4), a
	;ld a, 0x55
	;ld (SSD1306_VBUFFER + SSD1306_VBUFFER_OFFSET + 5), a
	
	ld hl, SSD1306_VBUFFER
	ld a, SSD1306_I2C_ADDRESS
	ld (SSD1306_VBUFFER + 0), a
	ld a, 0x40
	ld (SSD1306_VBUFFER + 1), a
	ld de, SSD1306_VBUFFER_LEN
	call i2cs_W

	pop hl
	pop bc
	ret
;-----------------------------------------------------------------------
; Required:
; Return:
; Flag C = 0' if success, 1' if error
; Altered:
; a
;-----------------------------------------------------------------------
i2cs_ssd1306_Init:
	push bc
	push hl
	BOARD_LOAD_IO_ADDR(SIOA_ADDRESS)
	ld hl, SSD1306_CBUFFER

	ld a, SSD1306_DISPLAYOFF
	call i2cs_ssd1306_WrCmd
	ld a, SSD1306_SETDISPLAYCLOCKDIV
	call i2cs_ssd1306_WrCmd
	ld a, 0x80
	call i2cs_ssd1306_WrCmd

	ld a, SSD1306_SETMULTIPLEX
	call i2cs_ssd1306_WrCmd
	ld a, 64
	call i2cs_ssd1306_WrCmd

	ld a, SSD1306_SETDISPLAYOFFSET
	call i2cs_ssd1306_WrCmd
	ld a, 0x00
	call i2cs_ssd1306_WrCmd
	ld a, SSD1306_SETSTARTLINE | 0x3F
	call i2cs_ssd1306_WrCmd
	
	ld a, SSD1306_CHARGEPUMP
	call i2cs_ssd1306_WrCmd
	ld a, 0x14
	call i2cs_ssd1306_WrCmd
	
	ld a, SSD1306_MEMORYMODE
	call i2cs_ssd1306_WrCmd
	ld a, 0x00
	call i2cs_ssd1306_WrCmd
	
	ld a, SSD1306_SEGREMAP | 0x01
	call i2cs_ssd1306_WrCmd
	ld a, SSD1306_COMSCANDEC
	call i2cs_ssd1306_WrCmd
	
	ld a, SSD1306_SETCOMPINS
	call i2cs_ssd1306_WrCmd
	ld a, 0x12
	call i2cs_ssd1306_WrCmd
	
	ld a, SSD1306_SETCONTRAST
	call i2cs_ssd1306_WrCmd
	ld a, 0xCF
	call i2cs_ssd1306_WrCmd
	
	ld a, SSD1306_SETPRECHARGE
	call i2cs_ssd1306_WrCmd
	ld a, 0xF1
	call i2cs_ssd1306_WrCmd
	
	ld a, SSD1306_SETVCOMDETECT
	call i2cs_ssd1306_WrCmd
	ld a, 0x40
	call i2cs_ssd1306_WrCmd
	
	ld a, SSD1306_DISPLAYALLON_RESUME
	call i2cs_ssd1306_WrCmd

	ld a, SSD1306_NORMALDISPLAY
	call i2cs_ssd1306_WrCmd
	
	ld a, SSD1306_DEACTIVATE_SCROLL
	call i2cs_ssd1306_WrCmd
	
	DELAYMS(2)
	
	ld a, SSD1306_DISPLAYON
	call i2cs_ssd1306_WrCmd
	pop hl
	pop bc
	ret
	
	
	
